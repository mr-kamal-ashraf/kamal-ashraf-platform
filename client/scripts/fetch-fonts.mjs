/**
 * Downloads every platform font (src/config/fonts.ts) from Google Fonts and
 * self-hosts it:
 *
 *   public/fonts/<key>/<subset>-<weight|var>.woff2   the font files
 *   public/fonts/<key>/font.css                      its @font-face rules (admin previews)
 *   src/config/fonts.generated.ts                    the same CSS + preload paths,
 *                                                    inlined by app/layout.tsx
 *
 * Only the Arabic and Latin subsets are kept. Run after adding or changing a
 * font:  npm run fonts:fetch     (Node 22.18+ — it imports the .ts config directly)
 */
import { mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { FONT_META, FONTS } from "../src/config/fonts.ts";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC_DIR = path.join(ROOT, "public", "fonts");
const GENERATED = path.join(ROOT, "src", "config", "fonts.generated.ts");
const SUBSETS = ["arabic", "latin"];
// A current browser UA makes Google serve woff2 split into unicode-range subsets.
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36";

const FACE_RE = /\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g;

function prop(body, name) {
  const m = body.match(new RegExp(`${name}:\\s*([^;]+);`));
  return m ? m[1].trim() : null;
}

async function download(url, dest) {
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`${res.status} for ${url}`);
  await writeFile(dest, Buffer.from(await res.arrayBuffer()));
}

/** Arabic files to preload: the variable file, or 400 + the boldest weight ≤ 800. */
function pickPreloads(key, faces) {
  const arabic = faces.filter((f) => f.subset === "arabic");
  const variable = arabic.find((f) => f.weight.includes(" "));
  if (variable) return [`/fonts/${key}/${variable.file}`];
  const byWeight = new Map(arabic.map((f) => [Number(f.weight), f]));
  const regular = byWeight.get(400) ?? arabic[0];
  const bold = [800, 700, 600].map((w) => byWeight.get(w)).find(Boolean);
  return [...new Set([regular, bold].filter(Boolean).map((f) => `/fonts/${key}/${f.file}`))];
}

async function fetchFont(key) {
  const { family, google } = FONT_META[key];
  const url = `https://fonts.googleapis.com/css2?family=${family.replace(/ /g, "+")}:${google}&display=swap`;
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`${key}: Google Fonts answered ${res.status} (${url})`);
  const css = await res.text();

  const dir = path.join(PUBLIC_DIR, key);
  await rm(dir, { recursive: true, force: true });
  await mkdir(dir, { recursive: true });

  const faces = [];
  for (const [, subset, body] of css.matchAll(FACE_RE)) {
    if (!SUBSETS.includes(subset) || prop(body, "font-style") !== "normal") continue;
    const weight = prop(body, "font-weight");
    const src = body.match(/url\(([^)]+)\)/)?.[1];
    const range = prop(body, "unicode-range");
    if (!weight || !src || !range) throw new Error(`${key}: unexpected @font-face block`);
    const file = `${subset}-${weight.includes(" ") ? "var" : weight}.woff2`;
    faces.push({ subset, weight, file, src, range });
  }
  if (!faces.some((f) => f.subset === "arabic")) throw new Error(`${key}: no Arabic subset returned`);

  await Promise.all(faces.map((f) => download(f.src, path.join(dir, f.file))));

  const fontCss = faces
    .map(
      (f) =>
        `@font-face{font-family:"${family}";font-style:normal;font-weight:${f.weight};font-display:swap;` +
        `src:url(/fonts/${key}/${f.file}) format("woff2");unicode-range:${f.range}}`,
    )
    .join("\n");
  await writeFile(path.join(dir, "font.css"), fontCss + "\n");

  console.log(`✓ ${key.padEnd(11)} ${faces.length} files`);
  return { css: fontCss.replace(/\n/g, ""), preloads: pickPreloads(key, faces) };
}

const results = {};
for (const key of FONTS) results[key] = await fetchFont(key);

const lines = [
  "// GENERATED by scripts/fetch-fonts.mjs (`npm run fonts:fetch`) — do not edit by hand.",
  "// Server-side only: app/layout.tsx inlines the active font's rules. Importing this",
  "// from client code would ship every font's CSS to the browser.",
  'import type { FontKey } from "./fonts";',
  "",
  "/** Minified @font-face rules of each self-hosted font (Arabic + Latin subsets). */",
  "export const FONT_FACE_CSS: Record<FontKey, string> = {",
  ...FONTS.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(results[k].css)},`),
  "};",
  "",
  "/** Arabic font files to preload when the font is active. */",
  "export const FONT_PRELOADS: Record<FontKey, readonly string[]> = {",
  ...FONTS.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(results[k].preloads)},`),
  "};",
  "",
];
await writeFile(GENERATED, lines.join("\n"));
console.log(`\nWrote ${path.relative(ROOT, GENERATED)}`);

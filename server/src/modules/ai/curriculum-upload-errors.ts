export type CurriculumUploadErrorCode = keyof typeof CATALOG;

export interface UploadErrorDetails {
  /** HTTP status the AI server (n8n) or Bunny answered with. */
  upstreamStatus?: number;
  /** Low-level network error code, e.g. ECONNRESET / ETIMEDOUT. */
  networkCode?: string;
  /** `error_code` field n8n put in its JSON body. */
  upstreamErrorCode?: string;
}

export function uploadError(
  code: CurriculumUploadErrorCode,
  details?: UploadErrorDetails,
): ApiError {
  const def = CATALOG[code];
  return new ApiError(def.statusCode, def.message, {
    code,
    ...(details && Object.keys(details).length > 0 ? { details } : {}),
  });
}

/** n8n WF1 answers business failures with `{ ok:false, error_code }`. */
function codeFromN8nErrorCode(
  errorCode: string,
): CurriculumUploadErrorCode | undefined {
  switch (errorCode) {
    case "OUT_OF_CREDIT":
      return "AI_OUT_OF_CREDIT";
    case "UNAUTHORIZED":
      return "AI_BACKEND_UNAUTHORIZED";
    case "INVALID_PAYLOAD":
      return "INGEST_INVALID_PAYLOAD";
    case "WORKFLOW_FAILED":
      return "INGEST_WORKFLOW_FAILED";
    case "OCR_FAILED":
      return "INGEST_OCR_FAILED";
    case "OCR_NO_TEXT":
      return "INGEST_NO_TEXT_FOUND";
    default:
      return undefined;
  }
}

function codeFromHttpStatus(status: number): CurriculumUploadErrorCode {
  switch (status) {
    case 400:
      return "INGEST_INVALID_PAYLOAD";
    case 401:
    case 403:
      return "AI_BACKEND_UNAUTHORIZED";
    case 402:
      return "AI_OUT_OF_CREDIT";
    case 404:
      return "INGEST_WEBHOOK_NOT_FOUND";
    case 413:
      return "INGEST_PAYLOAD_TOO_LARGE";
    case 429:
      return "AI_RATE_LIMIT";
    case 500:
      return "INGEST_WORKFLOW_FAILED";
    case 502:
    case 503:
      return "AI_SERVER_DOWN";
    case 504:
      return "INGEST_TIMEOUT";
    default:
      return "AI_UPSTREAM_ERROR";
  }
}

function codeFromNetworkError(networkCode: string | undefined): CurriculumUploadErrorCode {
  switch (networkCode) {
    case "ECONNABORTED":
    case "ETIMEDOUT":
      return "INGEST_TIMEOUT";
    case "ENOTFOUND":
    case "EAI_AGAIN":
      return "AI_SERVER_ADDRESS_INVALID";
    case "CERT_HAS_EXPIRED":
    case "DEPTH_ZERO_SELF_SIGNED_CERT":
    case "SELF_SIGNED_CERT_IN_CHAIN":
    case "UNABLE_TO_VERIFY_LEAF_SIGNATURE":
    case "ERR_TLS_CERT_ALTNAME_INVALID":
      return "AI_TLS_ERROR";
    // Refused (never up) and reset/broken pipe (dropped mid-way) get the same
    // advice: wait for n8n to come back.
    default:
      return "AI_SERVER_DOWN";
  }
}

function readN8nErrorCode(data: unknown): string | undefined {
  if (data && typeof data === "object" && "error_code" in data) {
    const v = (data as { error_code?: unknown }).error_code;
    if (typeof v === "string" && v) return v;
  }
  return undefined;
}

/** Turn any failure of the n8n `/pdf-ingest` call into a specific ApiError. */
export function toIngestApiError(err: unknown): ApiError {
  if (err instanceof ApiError) return err;

  if (!axios.isAxiosError(err)) {
    logger.error("[ai.service] pdf-ingest failed before reaching n8n", { err });
    return uploadError("INGEST_FILE_READ_FAILED");
  }

  const status = err.response?.status;
  if (status !== undefined) {
    const upstreamErrorCode = readN8nErrorCode(err.response?.data);
    logger.error("[ai.service] pdf-ingest rejected by n8n", {
      status,
      upstreamErrorCode,
    });
    const code =
      (upstreamErrorCode && codeFromN8nErrorCode(upstreamErrorCode)) ||
      codeFromHttpStatus(status);
    return uploadError(code, {
      upstreamStatus: status,
      ...(upstreamErrorCode ? { upstreamErrorCode } : {}),
    });
  }

  logger.error("[ai.service] pdf-ingest could not reach n8n", {
    code: err.code,
    message: err.message,
  });
  return uploadError(codeFromNetworkError(err.code), {
    ...(err.code ? { networkCode: err.code } : {}),
  });
}

/**
 * n8n answered HTTP 200 — but that alone does not mean the book was indexed.
 * An empty body means the workflow ended without reaching its response node
 * (it crashed or was killed mid-run); `ok:false` is a business failure.
 */
export function assertIngestSucceeded(body: unknown): void {
  const isEmptyObject =
    typeof body === "object" &&
    body !== null &&
    Object.keys(body as object).length === 0;
  if (body === null || body === undefined || body === "" || isEmptyObject) {
    throw uploadError("INGEST_EMPTY_RESPONSE");
  }
  if (typeof body !== "object") {
    throw uploadError("INGEST_UNEXPECTED_RESPONSE");
  }

  const { ok, error_code } = body as { ok?: unknown; error_code?: unknown };
  if (ok === true) return;

  if (ok === false) {
    const upstreamErrorCode =
      typeof error_code === "string" && error_code ? error_code : undefined;
    throw uploadError(
      (upstreamErrorCode && codeFromN8nErrorCode(upstreamErrorCode)) ||
        "INGEST_REJECTED",
      upstreamErrorCode ? { upstreamErrorCode } : undefined,
    );
  }

  throw uploadError("INGEST_UNEXPECTED_RESPONSE");
}

/**
 * What the admin should be told when n8n reports (via the ingest-result
 * callback) that a background indexing run failed.
 */
export function describeIngestFailure(n8nErrorCode?: string): {
  code: CurriculumUploadErrorCode;
  message: string;
} {
  const code =
    (n8nErrorCode && codeFromN8nErrorCode(n8nErrorCode)) || "INGEST_WORKFLOW_FAILED";
  return { code, message: CATALOG[code].message };
}

/** Message for a book whose background indexing never reported back. */
export function stalledIngestMessage(): string {
  return CATALOG.INGEST_STALLED.message;
}

/** Turn a failed Bunny Storage upload of the book's cold copy into an ApiError. */
export function toBunnyUploadApiError(err: unknown): ApiError {
  if (err instanceof ApiError) return err;

  if (!axios.isAxiosError(err)) {
    logger.error("[ai.controller] reading the book before Bunny upload failed", { err });
    return uploadError("INGEST_FILE_READ_FAILED");
  }

  const status = err.response?.status;
  logger.error("[ai.controller] Bunny Storage upload failed", {
    status,
    code: err.code,
  });

  if (status === 401 || status === 403) {
    return uploadError("BUNNY_AUTH_FAILED", { upstreamStatus: status });
  }
  if (status === 404) {
    return uploadError("BUNNY_ZONE_NOT_FOUND", { upstreamStatus: status });
  }
  if (status === undefined && (err.code === "ECONNABORTED" || err.code === "ETIMEDOUT")) {
    return uploadError("BUNNY_TIMEOUT", { networkCode: err.code });
  }
  return uploadError("BUNNY_UPLOAD_FAILED", {
    ...(status !== undefined ? { upstreamStatus: status } : {}),
    ...(err.code ? { networkCode: err.code } : {}),
  });
}
